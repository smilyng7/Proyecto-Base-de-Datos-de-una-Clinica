-- ORACLE: SECCIÓN SEGURIDAD Y CONFIGURACIÓN MAESTRA
CREATE TABLE rol_sistema (
    id_rol NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR2(50) NOT NULL
);

CREATE TABLE modulo_sistema (
    id_modulo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_modulo VARCHAR2(100) NOT NULL
);

CREATE TABLE permiso_rol (
    id_permiso NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol NUMBER NOT NULL,
    id_modulo NUMBER NOT NULL,
    puede_leer NUMBER(1) DEFAULT 0 CHECK (puede_leer IN (0,1)),
    puede_escribir NUMBER(1) DEFAULT 0 CHECK (puede_escribir IN (0,1)),
    puede_eliminar NUMBER(1) DEFAULT 0 CHECK (puede_eliminar IN (0,1)),
    CONSTRAINT fk_oracle_perm_rol FOREIGN KEY (id_rol) REFERENCES rol_sistema(id_rol),
    CONSTRAINT fk_oracle_perm_mod FOREIGN KEY (id_modulo) REFERENCES modulo_sistema(id_modulo)
);

CREATE TABLE usuario (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) UNIQUE NOT NULL,
    password_hash CLOB NOT NULL,
    id_empleado NUMBER NOT NULL, -- FK Lógica a PostgreSQL
    id_rol NUMBER NOT NULL,
    estado VARCHAR2(20) DEFAULT 'activo',
    CONSTRAINT fk_oracle_user_rol FOREIGN KEY (id_rol) REFERENCES rol_sistema(id_rol)
);

-- ORACLE: SECCIÓN TARIFARIOS Y FINANZAS
CREATE TABLE aseguradora (
    id_aseguradora NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_ruc VARCHAR2(11) UNIQUE NOT NULL,
    razon_social VARCHAR2(150) NOT NULL,
    telefono VARCHAR2(15) NULL
);

CREATE TABLE plan_seguro (
    id_plan NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aseguradora NUMBER NOT NULL,
    nombre_plan VARCHAR2(100) NOT NULL,
    cobertura NUMBER(5,2) NOT NULL,
    CONSTRAINT fk_oracle_plan_aseg FOREIGN KEY (id_aseguradora) REFERENCES aseguradora(id_aseguradora) ON DELETE CASCADE
);

CREATE TABLE servicio_hospitalario (
    id_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_servicio VARCHAR2(150) NOT NULL UNIQUE,
    costo_sin_seguro NUMBER(10,2) NOT NULL CHECK (costo_sin_seguro >= 0)
);

CREATE TABLE tarifario (
    id_tarifario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servicio NUMBER NOT NULL,
    id_aseguradora NUMBER NOT NULL,
    costo_con_seguro NUMBER(10,2) NOT NULL CHECK (costo_con_seguro >= 0),
    CONSTRAINT fk_oracle_tar_serv FOREIGN KEY (id_servicio) REFERENCES servicio_hospitalario(id_servicio),
    CONSTRAINT fk_oracle_tar_aseg FOREIGN KEY (id_aseguradora) REFERENCES aseguradora(id_aseguradora),
    CONSTRAINT uq_tarifario UNIQUE (id_servicio, id_aseguradora)
);

-- ORACLE: SECCIÓN CAJA Y COMPROBANTES
CREATE TABLE caja (
    id_caja NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_caja VARCHAR2(100) NOT NULL,
    nro_terminal VARCHAR2(20) UNIQUE NOT NULL
);

CREATE TABLE cajero (
    id_cajero NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado NUMBER NOT NULL, -- FK Lógica a PostgreSQL
    id_turno NUMBER NOT NULL     -- FK Lógica a PostgreSQL
);

CREATE TABLE apertura_caja (
    id_apertura NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_caja NUMBER NOT NULL,
    id_cajero NUMBER NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    monto_inicial NUMBER(10,2) NOT NULL CHECK (monto_inicial >= 0),
    CONSTRAINT fk_oracle_ap_caja FOREIGN KEY (id_caja) REFERENCES caja(id_caja),
    CONSTRAINT fk_oracle_ap_cajero FOREIGN KEY (id_cajero) REFERENCES cajero(id_cajero)
);

CREATE TABLE comprobante_pago (
    id_comprobante NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR2(20) NOT NULL CHECK (tipo IN ('Boleta','Factura')),
    serie VARCHAR2(10) NOT NULL,
    correlativo VARCHAR2(20) NOT NULL,
    CONSTRAINT uq_comprobante UNIQUE (serie, correlativo)
);

CREATE TABLE metodo_pago (
    id_metodo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE facturacion (
    id_facturacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente NUMBER NOT NULL, -- FK Lógica a PostgreSQL
    id_comprobante NUMBER NOT NULL,
    fecha_emision TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    subtotal NUMBER(10,2) NOT NULL,
    igv NUMBER(10,2) NOT NULL,
    total NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_oracle_fact_comp FOREIGN KEY (id_comprobante) REFERENCES comprobante_pago(id_comprobante)
);

CREATE TABLE detalle_facturacion (
    id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_facturacion NUMBER NOT NULL,
    id_servicio NUMBER NOT NULL,
    cantidad NUMBER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMBER(10,2) NOT NULL,
    descuento_seguro NUMBER(10,2) DEFAULT 0,
    CONSTRAINT fk_oracle_det_fact FOREIGN KEY (id_facturacion) REFERENCES facturacion(id_facturacion),
    CONSTRAINT fk_oracle_det_serv FOREIGN KEY (id_servicio) REFERENCES servicio_hospitalario(id_servicio)
);

CREATE TABLE pago (
    id_pago NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_facturacion NUMBER NOT NULL,
    id_metodo NUMBER NOT NULL,
    monto_pagado NUMBER(10,2) NOT NULL CHECK (monto_pagado > 0),
    fecha_pago TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_oracle_pago_fact FOREIGN KEY (id_facturacion) REFERENCES facturacion(id_facturacion),
    CONSTRAINT fk_oracle_pago_metodo FOREIGN KEY (id_metodo) REFERENCES metodo_pago(id_metodo)
);


